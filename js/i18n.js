/*
 * KoomBei i18n - lightweight, dependency-free translation engine.
 *
 * How it works: English lives in the HTML as the source of truth. On load we
 * snapshot every visible text node (and translatable attributes), then swap
 * in dictionary entries keyed by the exact trimmed English string. Switching
 * back to English simply restores the snapshot, so no English dictionary is
 * ever needed and every page stays fully static.
 *
 * Dictionaries for fr / es / pt are registered at the bottom of this file
 * via KBI18N.setDict(). Add a new language by adding one dictionary and one
 * entry in LANGS.
 */
(function () {
  'use strict';

  /* Shared render pipeline - currency.js registers a pass here too, so
     language and currency re-render in a fixed order without fighting. */
  if (!window.KB) {
    window.KB = {
      passes: [],
      addPass: function (fn, prio) {
        this.passes.push({ fn: fn, prio: prio || 0 });
        this.passes.sort(function (a, b) { return a.prio - b.prio; });
      },
      render: function () {
        for (var i = 0; i < this.passes.length; i++) {
          try { this.passes[i].fn(); }
          catch (e) { if (window.console) console.error('KoomBei render pass failed:', e); }
        }
      }
    };
  }

  /* Shared dropdown factory for the nav pickers (language + currency). */
  if (!window.KB.picker) {
    window.KB.picker = function (opts) {
      var wrap = document.createElement('div');
      wrap.className = 'kb-picker';

      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'kb-picker-btn';
      btn.setAttribute('aria-haspopup', 'listbox');
      btn.setAttribute('aria-expanded', 'false');
      if (opts.ariaLabel) btn.setAttribute('aria-label', opts.ariaLabel);
      btn.innerHTML = (opts.icon || '') +
        '<span class="kb-code"></span>' +
        '<svg class="kb-caret" width="9" height="9" viewBox="0 0 24 24" fill="none" aria-hidden="true">' +
        '<path d="M6 9l6 6 6-6" stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/></svg>';

      var panel = document.createElement('div');
      panel.className = 'kb-picker-panel';
      panel.setAttribute('role', 'listbox');

      function close() { wrap.classList.remove('open'); btn.setAttribute('aria-expanded', 'false'); }
      function open() { wrap.classList.add('open'); btn.setAttribute('aria-expanded', 'true'); }

      opts.items.forEach(function (item) {
        var b = document.createElement('button');
        b.type = 'button';
        b.className = 'kb-picker-item';
        b.setAttribute('role', 'option');
        b.setAttribute('data-value', item.value);
        b.innerHTML = '<span>' + item.label + '</span>' +
          (item.meta ? '<span class="kb-item-code">' + item.meta + '</span>' : '');
        b.addEventListener('click', function () {
          close();
          opts.onSelect(item.value);
        });
        panel.appendChild(b);
      });

      btn.addEventListener('click', function (e) {
        e.stopPropagation();
        if (wrap.classList.contains('open')) close(); else open();
      });
      document.addEventListener('click', function (e) {
        if (!wrap.contains(e.target)) close();
      });
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') close();
      });

      wrap.appendChild(btn);
      wrap.appendChild(panel);

      return {
        el: wrap,
        setCode: function (txt) { btn.querySelector('.kb-code').textContent = txt; },
        setSelected: function (value) {
          var items = panel.querySelectorAll('.kb-picker-item');
          for (var i = 0; i < items.length; i++) {
            items[i].classList.toggle('selected', items[i].getAttribute('data-value') === value);
          }
        }
      };
    };
  }

  /* Container in the nav for both pickers; created once, reused by currency.js. */
  if (!window.KB.toolsContainer) {
    window.KB.toolsContainer = function () {
      var nav = document.querySelector('nav');
      if (!nav) return null;
      var tools = nav.querySelector('.nav-tools');
      if (!tools) {
        tools = document.createElement('div');
        tools.className = 'nav-tools';
        nav.insertBefore(tools, nav.querySelector('.nav-toggle'));
      }
      return tools;
    };
  }

  var LANGS = [
    { code: 'en', name: 'English' },
    { code: 'fr', name: 'Français' },
    { code: 'es', name: 'Español' },
    { code: 'pt', name: 'Português' }
  ];
  var STORE_KEY = 'kb-lang';
  var DICTS = {};

  function supported(code) {
    for (var i = 0; i < LANGS.length; i++) if (LANGS[i].code === code) return true;
    return false;
  }

  function detect() {
    try {
      var saved = localStorage.getItem(STORE_KEY);
      if (saved && supported(saved)) return saved;
    } catch (e) { /* storage unavailable */ }
    var prefs = navigator.languages || [navigator.language || 'en'];
    for (var i = 0; i < prefs.length; i++) {
      var code = String(prefs[i]).slice(0, 2).toLowerCase();
      if (supported(code)) return code;
    }
    return 'en';
  }

  var current = detect();
  var textSnapshot = null;
  var attrSnapshot = null;
  var ATTRS = ['placeholder', 'aria-label', 'title'];

  /* Never touch scripts, styles, or the chatbot's injected UI. */
  function excluded(el) {
    while (el) {
      if (el.nodeType === 1) {
        var tag = el.tagName;
        if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT' || tag === 'TEMPLATE') return true;
        if (el.id && el.id.indexOf('kb-') === 0) return true;
        if (el.getAttribute && el.getAttribute('data-no-i18n') !== null) return true;
      }
      el = el.parentNode;
    }
    return false;
  }

  function snapshot() {
    textSnapshot = [];
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
    var node;
    while ((node = walker.nextNode())) {
      if (!node.data || !node.data.replace(/\s+/g, '')) continue;
      if (excluded(node.parentNode)) continue;
      textSnapshot.push({ node: node, orig: node.data });
    }
    attrSnapshot = [];
    for (var a = 0; a < ATTRS.length; a++) {
      var els = document.querySelectorAll('[' + ATTRS[a] + ']');
      for (var i = 0; i < els.length; i++) {
        if (excluded(els[i])) continue;
        attrSnapshot.push({ el: els[i], attr: ATTRS[a], value: els[i].getAttribute(ATTRS[a]) });
      }
    }
  }

  function applyLanguage() {
    if (!textSnapshot) snapshot();
    var dict = current === 'en' ? null : (DICTS[current] || null);

    for (var i = 0; i < textSnapshot.length; i++) {
      var entry = textSnapshot[i];
      if (!entry.node.parentNode) continue; // node was replaced (e.g. counters)
      if (!dict) { entry.node.data = entry.orig; continue; }
      var key = entry.orig.replace(/\s+/g, ' ').trim();
      var tr = dict[key];
      if (tr) {
        var lead = entry.orig.match(/^\s*/)[0];
        var tail = entry.orig.match(/\s*$/)[0];
        entry.node.data = lead + tr + tail;
      } else {
        entry.node.data = entry.orig;
      }
    }

    for (var j = 0; j < attrSnapshot.length; j++) {
      var it = attrSnapshot[j];
      if (!dict) { it.el.setAttribute(it.attr, it.value); continue; }
      var atr = dict[it.value.trim()];
      it.el.setAttribute(it.attr, atr || it.value);
    }

    document.documentElement.lang = current;
    if (picker) {
      picker.setCode(current.toUpperCase());
      picker.setSelected(current);
    }
  }

  var picker = null;

  function buildPicker() {
    var tools = window.KB.toolsContainer();
    if (!tools || tools.querySelector('.kb-lang-picker')) return;
    picker = window.KB.picker({
      ariaLabel: 'Language',
      icon: '<svg width="12" height="12" viewBox="0 0 20 20" fill="none" aria-hidden="true">' +
        '<circle cx="10" cy="10" r="8" stroke="currentColor" stroke-width="1.4"/>' +
        '<path d="M2 10h16M10 2c2.6 2.6 2.6 13.4 0 16M10 2c-2.6 2.6-2.6 13.4 0 16" stroke="currentColor" stroke-width="1.1"/></svg>',
      items: LANGS.map(function (l) {
        return { value: l.code, label: l.name, meta: l.code.toUpperCase() };
      }),
      onSelect: function (code) {
        current = code;
        try { localStorage.setItem(STORE_KEY, code); } catch (e) { /* ignore */ }
        window.KB.render();
      }
    });
    picker.el.classList.add('kb-lang-picker');
    tools.appendChild(picker.el);
  }

  window.KB.i18n = {
    t: function (key) {
      var dict = current === 'en' ? null : DICTS[current];
      return (dict && dict[key]) || key;
    },
    get lang() { return current; }
  };

  window.KBI18N = {
    setDict: function (code, dict) { DICTS[code] = dict; }
  };

  function boot() {
    buildPicker();
    window.KB.addPass(applyLanguage, 0);
    window.KB.render();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();

